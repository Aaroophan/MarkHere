import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const repo = fileURLToPath(new URL('..', import.meta.url))
const roots = ['apps', 'packages']
const nodes = new Map()

for (const root of roots) {
  for (const ent of await readdir(join(repo, root), { withFileTypes: true })) {
    if (!ent.isDirectory()) continue
    let manifest
    try {
      manifest = JSON.parse(await readFile(join(repo, root, ent.name, 'package.json'), 'utf8'))
    } catch {
      continue
    }
    const all = {
      ...(manifest.dependencies ?? {}),
      ...(manifest.devDependencies ?? {}),
      ...(manifest.optionalDependencies ?? {})
    }
    nodes.set(
      manifest.name,
      Object.keys(all).filter((name) => name.startsWith('@markhere/')).sort()
    )
  }
}

const lines = [
  '# MarkHere Workspace Dependency Graph',
  '',
  '> Generated by `pnpm graph:dependencies`. This graph includes only internal workspace dependencies.',
  '',
  '```mermaid',
  'flowchart LR'
]

const idFor = (name) => name.replace(/[^A-Za-z0-9]/g, '_')
for (const name of [...nodes.keys()].sort()) {
  lines.push(`  ${idFor(name)}["${name}"]`)
}
for (const [name, deps] of [...nodes.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  for (const dep of deps) lines.push(`  ${idFor(name)} --> ${idFor(dep)}`)
}
lines.push('```', '')

const outDir = join(repo, 'artifacts', 'architecture')
await mkdir(outDir, { recursive: true })
await writeFile(join(outDir, 'dependency-graph.md'), `${lines.join('\n')}\n`)
console.log(`Dependency graph generated for ${nodes.size} workspace packages`)
